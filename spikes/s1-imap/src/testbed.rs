//! The local Docker testbed (tools/testbed): endpoints, test users and the testbed CA.

use std::path::PathBuf;
use std::sync::Arc;

use anyhow::Result;
use rustls::ClientConfig;

use crate::idle::Account;
use crate::net::{ConnectOptions, Endpoint, Login, Security};
use crate::sync::SyncOptions;

pub const PASSWORD: &str = "testbed-password";

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Server {
    pub name: &'static str,
    pub tls_port: u16,
    pub starttls_port: u16,
}

pub const DOVECOT: Server = Server {
    name: "dovecot",
    tls_port: 14993,
    starttls_port: 14143,
};
pub const DOVECOT_REV1: Server = Server {
    name: "dovecot-rev1",
    tls_port: 15993,
    starttls_port: 15143,
};
pub const STALWART: Server = Server {
    name: "stalwart",
    tls_port: 16993,
    starttls_port: 16143,
};
pub const SERVERS: [Server; 3] = [DOVECOT, DOVECOT_REV1, STALWART];

pub fn server(name: &str) -> Option<Server> {
    SERVERS.into_iter().find(|s| s.name == name)
}

fn testbed_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../tools/testbed")
}

/// `MAIL_TESTBED_CA`, else `tools/testbed/certs/ca.pem` (generated by `tools/testbed/up.sh`).
pub fn ca_path() -> PathBuf {
    std::env::var_os("MAIL_TESTBED_CA")
        .map(PathBuf::from)
        .unwrap_or_else(|| testbed_dir().join("certs/ca.pem"))
}

pub fn cert_paths() -> (PathBuf, PathBuf) {
    let certs = testbed_dir().join("certs");
    (certs.join("server.pem"), certs.join("server.key"))
}

pub fn tls() -> Result<Arc<ClientConfig>> {
    crate::tls::with_roots(&ca_path())
}

pub fn endpoint(server: Server, security: Security) -> Endpoint {
    let port = match security {
        Security::Tls => server.tls_port,
        Security::StartTls => server.starttls_port,
    };
    Endpoint {
        host: "127.0.0.1".into(),
        port,
        server_name: "localhost".into(),
        security,
    }
}

pub fn login(user: &str) -> Login {
    Login {
        user: user.into(),
        password: PASSWORD.into(),
    }
}

pub fn account(server: Server, user: &str) -> Result<Account> {
    Ok(Account {
        endpoint: endpoint(server, Security::Tls),
        tls: tls()?,
        login: login(user),
        connect: ConnectOptions::default(),
        sync: SyncOptions::default(),
    })
}
